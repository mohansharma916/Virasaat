/**
 * Maps an ISO 3166-1 2-letter country code (case-insensitive) to its full country name.
 */
export function getCountryNameByCode(code: string): string | null {
  if (!code) return null;
  const upper = code.trim().toUpperCase();
  const match = COUNTRIES.find((c) => c.code === upper);
  return match ? match.name : null;
}

/**
 * Client-side timezone heuristic fallback (instant, zero network latency).
 */
export function detectCountryFromTimeZone(): string | null {
  try {
    const tz = Intl.DateTimeFormat().resolvedOptions().timeZone;
    if (!tz) return null;

    if (tz === 'Asia/Calcutta' || tz === 'Asia/Kolkata') return 'India';
    if (tz.startsWith('America/New_York') || tz.startsWith('America/Los_Angeles') || tz.startsWith('America/Chicago') || tz.startsWith('America/Denver')) return 'United States';
    if (tz === 'Europe/London') return 'United Kingdom';
    if (tz === 'Asia/Dubai') return 'United Arab Emirates';
    if (tz === 'Asia/Singapore') return 'Singapore';
    if (tz === 'Asia/Kathmandu') return 'Nepal';
    if (tz === 'Asia/Dhaka') return 'Bangladesh';
    if (tz === 'Asia/Karachi') return 'Pakistan';
    if (tz === 'Asia/Colombo') return 'Sri Lanka';
    if (tz.startsWith('Australia/')) return 'Australia';
    if (tz.startsWith('America/Toronto') || tz.startsWith('America/Vancouver')) return 'Canada';
    if (tz === 'Europe/Berlin') return 'Germany';
    if (tz === 'Europe/Paris') return 'France';
    if (tz === 'Asia/Tokyo') return 'Japan';
  } catch {}
  return null;
}

/**
 * Attempts to detect the user's country from IP (100% static & S3-compatible):
 * 1. https://api.country.is (instant client-side GeoIP lookup)
 * 2. Client timezone heuristic (zero network latency)
 * 3. Default fallback: "India"
 */
export async function fetchCountryFromIp(): Promise<string> {
  // 1. Try fast client-side GeoIP (api.country.is)
  try {
    const controller = new AbortController();
    const timeout = setTimeout(() => controller.abort(), 2000);
    const res = await fetch('https://api.country.is', { signal: controller.signal });
    clearTimeout(timeout);
    if (res.ok) {
      const data = await res.json();
      if (data?.country) {
        const mapped = getCountryNameByCode(data.country);
        if (mapped) return mapped;
      }
    }
  } catch {}

  // 2. Try client-side Timezone heuristic
  const tzMatch = detectCountryFromTimeZone();
  if (tzMatch) return tzMatch;

  // 3. Default fallback: India
  return 'India';
}
